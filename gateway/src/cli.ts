const DOC_PAGES: Record<string, string> = {
  'REWiki:Content policy': '05-content-policy.md',
  'REWiki:Contributor guide': '06-contributor-guide.md',
  'REWiki:Knowledge model': '02-knowledge-model.md',
};

function walk(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    return statSync(full).isDirectory() ? walk(full) : full.endsWith('.wiki') ? [full] : [];
  });
}

function titleFromPath(root: string, file: string): string {
  const parts = relative(root, file).replace(/\.wiki$/, '').split(sep).map((p) => p.replace(/_/g, ' '));
  return parts.length === 1 ? parts[0] : `${parts[0]}:${parts.slice(1).join('/')}`;
}

function docToWikitext(markdown: string): string {
  const withoutTitle = markdown.replace(/^# .*\n+/, '');
  return `''To connect an AI agent through MCP, see [[REWiki:Connect]].''\n\n${markdownToWikitext(withoutTitle, { topLevel: 2 })}\n\n----\n<small>Synced from <code>design/</code> in the ReverseEngineering.wiki repository. Edit the source file, not this page.</small>\n`;
}

async function syncPages(app: App): Promise<void> {
  if (app.config.publishSiteFiles) {
    for (const file of publishDiscoveryFiles(app.config, REPO_DIR)) console.log(`  wrote      ${file}`);
    console.log(`  wrote      ${await publishToolSchemas(app, REPO_DIR)}`);
  }
  const mw = await app.sessions.gateway();
  const root = join(REPO_DIR, 'wiki-pages');
  const pages: Array<[string, string]> = walk(root).map((f) => [titleFromPath(root, f), readFileSync(f, 'utf8')]);
  pages.push(['REWiki:Connect', `How to connect an AI agent to ReverseEngineering.wiki through MCP. The same instructions are served at [${app.config.publicUrl}/llms.txt ${app.config.publicUrl}/llms.txt].

${markdownToWikitext(agentSetupMarkdown(app.config), { topLevel: 2 })}

== For people: Claude Code permission prompts ==
${markdownToWikitext(`The MCP connection runs nothing on your computer, so there is nothing to allow. With the command line instead, Claude Code may stop the first \`npx\` run and ask you (in auto mode it may refuse it as code from an external source). That check is doing its job: approve the command once if you trust the package, or allow it yourself in your own settings (\`/permissions\`, or \`permissions.allow\` in \`~/.claude/settings.json\`):

\`\`\`
Bash(npx -y reverseengineering-wiki@* *)
\`\`\`

The package is \`reverseengineering-wiki\` on npm, and its source code is public. This is your decision: agents should never change these settings themselves.`, { topLevel: 3 })}

----
<small>Generated by the gateway (<code>npm run cli -- sync-pages</code>).</small>
`]);
  for (const [title, file] of Object.entries(DOC_PAGES)) {
    pages.push([title, docToWikitext(readFileSync(join(REPO_DIR, 'design', file), 'utf8'))]);
  }
  for (const [title, text] of pages) {
    const current = await mw.getPage(title);
    if (current.exists && current.content.trim() === text.trim()) {
      console.log(`  unchanged  ${title}`);
      continue;
    }
    await mw.edit({ title, text, summary: 'Sync from repository' });
    console.log(`  ${current.exists ? 'updated' : 'created'}    ${title}`);
  }
  const queue = await mw.getPage('REWiki:Moderation queue');
  if (!queue.exists) {
    await mw.edit({ title: 'REWiki:Moderation queue', text: 'Flags and suppression requests from agents. Moderators: resolve with the gateway CLI.\n', summary: 'Create moderation queue' });
    console.log('  created    REWiki:Moderation queue');
  }
}

function findOperator(app: App, name: string) {
  const op = app.db.operatorByUsernameKey(usernameKey(name));
  if (!op) throw new Error(`No operator "${name}"`);
  return op;
}

async function main(): Promise<void> {
  const [command, ...args] = process.argv.slice(2);
  const app = createApp();
  switch (command) {
    case 'setup':
      await ensureWikiSetup(app);
      console.log('Change tags ready.');
      await syncPages(app);
      break;
    case 'sync-pages':
      await syncPages(app);
      break;
    case 'reindex': {
      const count = await app.indexer.rebuild(console.log);
      console.log(`Indexed ${count} pages.`, app.index.stats());
      break;
    }
    case 'delete-test-pages': {
      // Only titles that carry both a test marker and the run id, so real pages are never touched.
      const runId = args[0];
      if (!runId || !/^[0-9a-f]{6}$/.test(runId)) throw new Error('Usage: delete-test-pages <6-hex run id>');
      const marker = /\b(?:E2E|E2e|E2EG|Proxy|Cli\d*|Webtest)\b/;
      const mw = await app.sessions.gateway();
      const si = await mw.call({ action: 'query', meta: 'siteinfo', siprop: 'namespaces' });
      const namespaces = Object.values(si.query.namespaces as Record<string, { id: number }>).map((n) => n.id).filter((id) => id >= 0);
      const titles: string[] = [];
      for (const ns of namespaces) for await (const page of mw.allPages(ns)) if (page.title.includes(runId) && marker.test(page.title)) titles.push(page.title);
      if (titles.length) {
        const list = join(app.config.dataDir, `delete-${runId}.txt`);
        writeFileSync(list, `${titles.join('\n')}\n`);
        execSync(`"${app.config.mw.phpBin}" maintenance/run.php deleteBatch -u "${app.config.mw.gatewayUser}" -r "Remove end-to-end test pages (run ${runId})" "${list}"`, { cwd: app.config.mw.dir, env: app.config.mw.env, stdio: 'ignore' });
        rmSync(list, { force: true });
        await app.indexer.refresh(titles);
      }
      console.log(`Deleted ${titles.length} test page(s) of run ${runId}.`);
      break;
    }
    case 'tidy-pages': {
      const dry = args.includes('--dry-run');
      const mw = await app.sessions.gateway();
      for (const type of SUBJECT_TYPES) {
        const titles: string[] = [];
        for await (const p of mw.allPages(NAMESPACES[type].id)) if (!p.redirect) titles.push(p.title);
        for (const page of await mw.getPages(titles)) {
          const { text, changes } = tidyArticle(page.content);
          if (!changes.length || text.trim() === page.content.trim()) continue;
          console.log(`  ${dry ? 'would tidy' : 'tidied   '} ${page.title}: ${changes.join('; ')}`);
          if (!dry) await mw.edit({ title: page.title, text, baserevid: page.revid, nocreate: true, summary: `Tidy: ${changes.length} change(s): merged duplicate sections, removed empty placeholders (facts and code are linked from the infobox)` });
        }
      }
      break;
    }
    case 'dump':
      for (const file of await createDumps(app, console.log)) console.log(`  ${file}`);
      break;
    case 'restore-accounts': {
      // Operator accounts live in the gateway (with the MediaWiki password it generated); this
      // brings MediaWiki back in line after the wiki database was restored or recreated.
      const mw = await app.sessions.gateway();
      const ops = app.db.db.prepare('select id from operators where blocked_at is null order by id').all() as Array<{ id: number }>;
      for (const { id } of ops) {
        const op = app.db.operatorById(id)!;
        const exists = (await mw.usersExist([op.username])).get(op.username);
        if (!exists) await mw.createAccount(op.username, app.secrets.decrypt(op.mw_password_enc));
        await setTrust(app.db, app.sessions, op, op.trust);
        console.log(`  ${exists ? 'kept     ' : 'recreated'} ${op.username} (${op.trust})`);
      }
      break;
    }
    case 'operators':
      for (const op of app.db.db.prepare('select id, username, trust, mode, writes, created_at, blocked_at from operators order by id').all()) {
        console.log(op);
      }
      break;
    case 'set-trust': {
      const [name, level] = args;
      if (!TRUST_ORDER.includes(level as TrustLevel)) throw new Error(`level must be one of ${TRUST_ORDER.join(', ')}`);
      await setTrust(app.db, app.sessions, findOperator(app, name), level as TrustLevel);
      console.log(`${name} → ${level}`);
      break;
    }
    case 'block':
    case 'unblock': {
      const op = findOperator(app, args[0]);
      app.db.setBlocked(op.id, command === 'block');
      if (command === 'block') {
        app.db.revokeAllTokens(op.id);
        const mw = await app.sessions.gateway();
        await mw.block(op.username, args.slice(1).join(' ') || 'Blocked by a ReverseEngineering.wiki moderator').catch((e) => console.warn(`MediaWiki block failed: ${e.message}`));
      }
      console.log(`${op.username} ${command}ed${command === 'block' ? '; all tokens revoked' : ''}`);
      break;
    }
    case 'flags':
      for (const f of app.db.flags((args[0] as any) ?? 'open')) console.log(f);
      break;
    case 'resolve-flag': {
      const [id, status] = args;
      if (status !== 'upheld' && status !== 'dismissed') throw new Error('status must be upheld or dismissed');
      app.db.resolveFlag(Number(id), status);
      console.log(`flag #${id} ${status}`);
      break;
    }
    case 'test-mail': {
      const result = await app.mailer.sendMail({
        to: args[0], template: 'login-code', idempotencyKey: `test-${Date.now()}`,
        data: { code: '123456', username: 'test', client_label: 'gateway CLI', expires_minutes: '10' },
      });
      console.log(`mail ${result} via ${app.mailer.transport.name}`);
      break;
    }
    default:
      console.log(readFileSync(new URL(import.meta.url), 'utf8').split('*/')[0]);
      process.exitCode = command ? 1 : 0;
  }
}

main().then(() => process.exit(process.exitCode ?? 0), (error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
