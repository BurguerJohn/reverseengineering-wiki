/**
 * Gateway CLI.
 *   setup                       create change tags and sync project pages
 *   sync-pages                  push wiki-pages/ and policy docs to the wiki
 *   reindex                     rebuild the search index from MediaWiki
 *   dump                        write downloadable dumps
 *   tidy-pages [--dry-run]      merge duplicate sections, drop empty placeholders (older pages)
 *   delete-test-pages <run id>  delete the pages an end-to-end test run created (the test scripts call it)
 *   restore-accounts            recreate in MediaWiki every operator account the gateway knows (after a wiki restore)
 *   operators                   list operator accounts
 *   set-trust <user> <level>    new | established | trusted | curator
 *   block <user> / unblock <user>
 *   flags [open|upheld|dismissed]
 *   resolve-flag <id> <upheld|dismissed>
 *   test-mail <address>         send a test login-code email through the configured driver
 */
import { execSync } from 'node:child_process';
import { readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { REPO_DIR } from './config.ts';
import { createApp, ensureWikiSetup, type App } from './app.ts';
import { createDumps } from './dumps.ts';
import { tidyArticle } from './wiki/tidy.ts';
import { NAMESPACES, SUBJECT_TYPES } from './wiki/titles.ts';
import { agentSetupMarkdown, publishDiscoveryFiles, publishToolSchemas } from './http/discovery.ts';
import { markdownToWikitext } from './wiki/markdown.ts';
import { setTrust, TRUST_ORDER } from './auth/trust.ts';
import { usernameKey } from './auth/usernames.ts';
