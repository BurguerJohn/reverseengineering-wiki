/**
 * export_header / export_symbols: turn facts into artifacts other agents can
 * import directly (C headers, Ghidra/IDA scripts). Every value that reaches
 * generated code is sanitized: names become identifiers, text becomes JSON
 * string literals in comments-free positions.
 */
import type { Services } from './context.ts';
import { ToolError } from './context.ts';
import { normalizeTitle, requireTitle, SUBJECT_TYPES, TitleError, type PageType } from '../wiki/titles.ts';

const HEADER_NOTE = 'Generated by ReverseEngineering.wiki from community facts. Facts marked "claimed" are unverified. Generated code: MIT-0.';

function ident(raw: unknown, fallback: string): string {
  const s = String(raw ?? '').replace(/[^A-Za-z0-9_]/g, '_').replace(/^(\d)/, '_$1').slice(0, 120);
  return s && /[A-Za-z_]/.test(s) ? s : fallback;
}

function qualifiedName(raw: unknown, fallback: string): string {
  // C++ scopes (Foo::Bar), Go and Rust paths (runtime.main, net/http.(*Client).Do): Ghidra and IDA (SN_NOCHECK)
  // accept them; only whitespace, quotes and control characters become "_".
  const s = String(raw ?? '').replace(/[^A-Za-z0-9_:~<>.$@?/*()[\],\-]/g, '_').slice(0, 200);
  return s && /[A-Za-z_]/.test(s) ? s : fallback;
}

function comment(text: unknown): string {
  return String(text ?? '').replace(/[^\x20-\x7e]/g, '?').replace(/\*\//g, '* /').slice(0, 160);
}

function hexNum(raw: unknown): number | null {
  if (typeof raw === 'number' && Number.isFinite(raw)) return raw;
  if (typeof raw === 'string' && /^0x[0-9a-f]+$/i.test(raw.trim())) return parseInt(raw.trim(), 16);
  if (typeof raw === 'string' && /^\d+$/.test(raw.trim())) return parseInt(raw.trim(), 10);
  return null;
}

const C_TYPE = /^(?:const\s+)?(?:(?:struct|enum|union)\s+)?(?:unsigned\s+|signed\s+)?(?:long\s+long(?:\s+int)?|long\s+double|long\s+int|short\s+int|[A-Za-z_][\w]*)(?:\s*\*+(?:\s*const\b)?)*\s*$/;
/** "void (*)(void)", "int (*)(Entity *, int)": a function pointer type. */
const FN_POINTER = /^[A-Za-z_][\w\s*]*\(\s*\*\s*\)\s*\([\w\s*,.]*\)$/;

/** The type name a field uses by value or through a pointer ("struct Entity *" → Entity). */
function baseType(type: string): string {
  return type.replace(/^const\s+/, '').replace(/^(?:struct|enum|union)\s+/, '').replace(/\s*\*.*$/, '').trim();
}

/**
 * Structs in an order C accepts: one used by value comes before the struct that contains it.
 * (Pointers are fine in any order: every struct also gets a forward declaration.)
 */
function dependencyOrder<T extends { kind: string; data: string }>(facts: T[], name: (f: T) => string): T[] {
  const structs = facts.filter((f) => f.kind === 'struct');
  const byName = new Map(structs.map((f) => [name(f), f]));
  const out: T[] = [];
  const state = new Map<string, 'visiting' | 'done'>();
  const visit = (f: T) => {
    const n = name(f);
    if (state.get(n)) return;
    state.set(n, 'visiting');
    for (const field of JSON.parse(f.data).fields ?? []) {
      const t = String(field?.type ?? '');
      if (t.includes('*')) continue;
      const dep = byName.get(baseType(t.replace(/\[.*$/, '')));
      if (dep && state.get(name(dep)) !== 'visiting') visit(dep);
    }
    state.set(n, 'done');
    out.push(f);
  };
  for (const f of structs) visit(f);
  return [...facts.filter((f) => f.kind === 'enum'), ...out, ...facts.filter((f) => f.kind !== 'enum' && f.kind !== 'struct')];
}
const BUILTIN = /^(?:const\s+)?(?:(?:unsigned|signed)\b(?:\s+(?:char|short|int|long(?:\s+long)?))?|(?:unsigned\s+|signed\s+)?(?:u?int(?:8|16|32|64)_t|u?intptr_t|size_t|ptrdiff_t|char|short|int|long|long long|float|double|void|bool|_Bool|wchar_t|BYTE|WORD|DWORD|QWORD|BOOL)\b)/;

/** A field name that is a description ("type (0 = saved game)"): a short identifier, the rest as a comment. */
function fieldName(raw: unknown): { name: string; rest?: string } {
  const text = String(raw ?? '').trim();
  if (/^[A-Za-z_]\w*$/.test(text)) return { name: text };
  // "64GB_LINK_CABLE": an identifier but for the leading digit; keep it whole.
  if (/^\d\w*$/.test(text)) return { name: `_${text}` };
  const first = /[A-Za-z_]\w*/.exec(text)?.[0] ?? '';
  return { name: ident(first, ''), rest: text };
}

/**
 * Integer and float types as agents spell them: "uint8", "u32", "int16_le", "uint32_be", "f32" become
 * stdint/float types; a stated byte order goes into the comment.
 */
function stdType(raw: string): { type: string; order?: string } | null {
  const m = /^(?:(u|s|i)(8|16|32|64)|(u?)int(8|16|32|64)(?:_t)?|(f|float)(32|64))(?:[_ ]?(be|le))?$/i.exec(raw.trim());
  if (!m) return null;
  const order = m[7] ? (m[7].toLowerCase() === 'be' ? 'big-endian' : 'little-endian') : undefined;
  if (m[5]) return { type: m[6] === '32' ? 'float' : 'double', order };
  const unsigned = m[1] ? m[1].toLowerCase() === 'u' : m[3] === 'u' || m[3] === 'U';
  return { type: `${unsigned ? 'u' : ''}int${m[2] ?? m[4]}_t`, order };
}

function cType(raw: unknown): string | null {
  const s = String(raw ?? '').trim();
  return C_TYPE.test(s) ? s : null;
}

/**
 * Enum values as agents write them: {"0": "Rifle"} (the documented form), {"Rifle": 0},
 * [{name, value}] or ["Rifle", "Shotgun"].
 */
/** Enum values may be negative ("-1", -14): hexNum only reads unsigned numbers. */
function signedNum(raw: unknown): number | null {
  if (typeof raw === 'number' && Number.isInteger(raw)) return raw;
  if (typeof raw === 'string' && /^-\d+$/.test(raw.trim())) return parseInt(raw.trim(), 10);
  if (typeof raw === 'string' && /^-0x[0-9a-f]+$/i.test(raw.trim())) return -parseInt(raw.trim().slice(3), 16);
  // Character codes ("'A'", as mangling letters and opcodes are often written).
  if (typeof raw === 'string' && /^'[\x20-\x7e]'$/.test(raw.trim())) return raw.trim().charCodeAt(1);
  return hexNum(raw);
}

/** An enum value exactly, 64-bit included (a double rounds 0x4000000000000001 to 0x4000000000000000). */
function enumNum(raw: unknown): bigint | null {
  if (typeof raw === 'bigint') return raw;
  if (typeof raw === 'number') return Number.isSafeInteger(raw) ? BigInt(raw) : null;
  if (typeof raw !== 'string') return null;
  const t = raw.trim();
  if (/^-?\d+$/.test(t)) return BigInt(t);
  if (/^-?0x[0-9a-f]+$/i.test(t)) return t.startsWith('-') ? -BigInt(t.slice(1)) : BigInt(t);
  const n = signedNum(raw);
  return n === null ? null : BigInt(n);
}

/** "0x80-0x9F", "128..159": a range of values sharing one name (control bytes, opcode classes). */
const VALUE_RANGE = /^\s*(-?(?:0x[0-9a-f]+|\d+))\s*(?:-|–|\.\.)\s*(-?(?:0x[0-9a-f]+|\d+))\s*$/i;

type EnumValue = { name: string; value: bigint | null; end?: bigint; notes?: string };

function enumValues(raw: unknown): EnumValue[] {
  const notesOf = (v: any) => (v && typeof v === 'object' && typeof v.notes === 'string' ? v.notes : undefined);
  const range = (text: unknown): { value: bigint; end: bigint } | null => {
    const m = typeof text === 'string' ? VALUE_RANGE.exec(text) : null;
    return m ? { value: enumNum(m[1])!, end: enumNum(m[2])! } : null;
  };
  let out: EnumValue[] = [];
  if (Array.isArray(raw)) {
    out = raw.map((v, i) => (typeof v === 'string' ? { name: v, value: BigInt(i) }
      : { name: String(v?.name ?? ''), ...(range(v?.value) ?? { value: enumNum(v?.value) }), notes: notesOf(v) }));
    return out;
  }
  if (raw && typeof raw === 'object') {
    out = Object.entries(raw as Record<string, unknown>).map(([k, v]): EnumValue => {
      const keyRange = range(k);
      if (keyRange && typeof v === 'string') return { name: v, ...keyRange };
      const keyNumber = enumNum(k);
      if (keyNumber !== null && typeof v === 'string') return { name: v, value: keyNumber };
      const valueRange = range(v);
      if (valueRange) return { name: k, ...valueRange };
      const valueNumber = enumNum(v);
      if (valueNumber !== null) return { name: k, value: valueNumber };
      if (v && typeof v === 'object' && 'value' in v) return { name: k, ...(range((v as any).value) ?? { value: enumNum((v as any).value) }), notes: notesOf(v) };
      return { name: k, value: null };
    });
    return out.sort((a, b) => { const x = a.value ?? 0n; const y = b.value ?? 0n; return x < y ? -1 : x > y ? 1 : 0; });
  }
  return [];
}

function enumLiteral(v: bigint): string {
  // Small negatives read best in decimal (-1, -2), error codes in hex (-0x7000).
  return v < 0n ? (v > -256n ? String(v) : `-0x${(-v).toString(16).toUpperCase()}`) : `0x${v.toString(16).toUpperCase()}`;
}

let sIndex: Services['index'] | undefined;
let knownStructs = new Set<string>();

function cleanTitle(raw: string, allowed: readonly PageType[]): string {
  try {
    return requireTitle(raw, allowed, (t) => !!sIndex?.page(t));
  } catch (error) {
    if (error instanceof TitleError) throw new ToolError('BAD_TITLE', error.message);
    throw error;
  }
}

export function exportHeader(s: Services, args: { subject: string; build?: string; abi?: string }) {
  sIndex = s.index;
  const subject = s.index.resolveRedirect(cleanTitle(args.subject, SUBJECT_TYPES));
  const build = args.build ? normalizeTitle(args.build) : null;
  const all = s.index.factsForSubject(subject, ['struct', 'enum', 'vtable', 'typedef'])
    .filter((f) => !build || f.level !== 'build' || f.applies_to === build)
    .filter((f) => f.status !== 'rejected');
  const warnings: string[] = [];
  // One layout per name: the ABI asked for, else the one without an ABI, else the first (with a warning).
  const abiOf = (f: { data: string }) => { try { const a = JSON.parse(f.data).abi; return typeof a === 'string' ? a.trim().toLowerCase() : ''; } catch { return ''; } };
  const nameOf = (f: { kind: string; data: string }) => { try { const d = JSON.parse(f.data); return `${f.kind === 'typedef' ? 'typedef' : 'type'}:${d.name ?? d.class}`; } catch { return f.kind; } };
  const wanted = args.abi?.trim().toLowerCase();
  const abis = [...new Set(all.map(abiOf).filter(Boolean))].sort();
  const groups = new Map<string, typeof all>();
  for (const f of all) groups.set(nameOf(f), [...(groups.get(nameOf(f)) ?? []), f]);
  const facts = [...groups.values()].flatMap((g) => {
    if (g.length === 1 && (!wanted || !abiOf(g[0]) || abiOf(g[0]) === wanted)) return g;
    const pick = (wanted ? g.find((f) => abiOf(f) === wanted) : undefined) ?? g.find((f) => !abiOf(f)) ?? (wanted ? undefined : [...g].sort((a, b) => abiOf(a).localeCompare(abiOf(b)))[0]);
    if (!wanted && g.length > 1 && pick && abiOf(pick)) warnings.push(`${nameOf(pick).split(':')[1]} has layouts for ${g.map(abiOf).join(', ')}: this header uses ${abiOf(pick)} (pass abi to choose).`);
    return pick ? [pick] : [];
  }).sort((a, b) => all.indexOf(a) - all.indexOf(b));
  // A format's byte order (its infobox): fields are stored that way, whatever the machine reading them.
  let endianness = '';
  try { endianness = String(JSON.parse(s.index.page(subject)?.json ?? '{}').infobox?.endianness ?? '').trim(); } catch { /* no infobox */ }
  const lines = [`/* ${HEADER_NOTE}`, ` * Subject: ${comment(subject)}${build ? `\n * Build: ${comment(build)}` : ''}${wanted ? `\n * ABI: ${comment(wanted)}` : abis.length ? `\n * ABIs with their own layouts: ${abis.map(comment).join(', ')} (pass abi)` : ''}`,
    ...(endianness ? [` * Byte order of the format: ${comment(endianness)}${/big/i.test(endianness) ? ' (swap multi-byte fields on little-endian machines)' : ''}`] : []),
    ` * Generated: ${new Date().toISOString()} */`, '#pragma once', '#include <stddef.h>', '#include <stdint.h>', ''];
  const skipped: string[] = [];
  const unknownTypes = new Set<string>();
  // Types defined in this header; others come from other pages and must still compile here.
  const typeName = (f: { kind: string; data: string }) => {
    try {
      const d = JSON.parse(f.data);
      return f.kind === 'vtable' ? ident(`${d.class}_vtbl`, '') : ident(fieldName(d.name).name, '');
    } catch {
      return '';
    }
  };
  const defined = new Set(facts.map(typeName));
  // Struct names defined on other subjects' pages, to tell "defined on another page" from "not defined anywhere".
  knownStructs = new Set(s.index.structNames().map((n) => ident(fieldName(n).name, '')));
  const forward = new Set<string>();
  const enumConstants = new Set<string>();
  // Every struct is declared first, so pointers between them work in any order.
  const declared = facts.filter((f) => f.kind !== 'enum' && f.kind !== 'typedef').map(typeName).filter(Boolean);
  if (declared.length) lines.push(...declared.map((t) => `typedef struct ${t} ${t};`), '');
  const typedefs = facts.filter((f) => f.kind === 'typedef');
  for (const f of typedefs) {
    const d = JSON.parse(f.data);
    const target = String(d.type ?? '').trim();
    const std = stdType(target);
    const ctype = std ? std.type : target;
    const name = ident(String(d.name ?? ''), '');
    if (!name) continue;
    if (FN_POINTER.test(ctype)) lines.push(`typedef ${ctype.replace(/\(\s*\*\s*\)/, `(*${name})`)}; /* [${f.status}] ${comment(f.title)} */`);
    else if (cType(ctype)) {
      const base = baseType(ctype);
      // A pointer to a struct no fact defines still compiles; by value it needs the struct.
      if (!BUILTIN.test(ctype) && !defined.has(base) && ctype.includes('*') && !declared.includes(base)) forward.add(base);
      lines.push(`typedef ${ctype} ${name}; /* [${f.status}] ${comment(f.title)}${std?.order ? `; ${std.order}` : ''} */`);
    } else {
      lines.push(`/* typedef ${comment(target)} ${name}: not a C type (${comment(f.title)}) */`);
      defined.delete(name);
    }
  }
  if (typedefs.length) lines.push('');
  for (const f of dependencyOrder(facts.filter((x) => x.kind !== 'typedef'), typeName)) {
    const data = JSON.parse(f.data);
    lines.push(`/* [${f.status}] ${comment(f.title)} */`);
    if (f.kind === 'struct') {
      const name = ident(fieldName(data.name).name, 'UnnamedStruct');
      const size = hexNum(data.size);
      const allFields = (Array.isArray(data.fields) ? data.fields : [])
        .map((x: any) => {
          const named = fieldName(x.name);
          // "uint32_be[4]" → "uint32_t[4]", byte order noted.
          const rawType = String(x.type ?? '').trim();
          const arrayPart = /((?:\[[^\]]*\])+)$/.exec(rawType)?.[1] ?? '';
          const std = stdType(rawType.slice(0, rawType.length - arrayPart.length));
          const typeText = std ? `${std.type}${arrayPart}` : rawType;
          const condition = typeof x.condition === 'string' && x.condition.trim() ? `present only if ${x.condition.trim()}` : '';
          return { offset: hexNum(x.offset), rawOffset: x.offset, size: hexNum(x.size), type: cType(typeText), rawType: typeText, name: named.name, notes: [condition, named.rest, std?.order, x.notes].filter(Boolean).join('; '), bits: Array.isArray(x.bits) ? x.bits : [] };
        });
      const fields = allFields.filter((x: any) => x.offset !== null).sort((a: any, b: any) => a.offset - b.offset);
      const floating = allFields.filter((x: any) => x.offset === null);
      const NATURAL: Record<string, number> = { int16_t: 2, uint16_t: 2, int32_t: 4, uint32_t: 4, float: 4, int64_t: 8, uint64_t: 8, double: 8, short: 2, 'unsigned short': 2, int: 4, unsigned: 4, 'unsigned int': 4, 'long long': 8, 'unsigned long long': 8 };
      const misaligned = fields.some((x: any) => {
        const n = x.type ? NATURAL[x.type.replace(/^const\s+/, '')] : undefined;
        return n !== undefined && x.offset % n !== 0;
      });
      // A declared size that is not a multiple of the widest field (IHDR: 13 bytes of uint32/uint8) means no tail padding.
      const widest = Math.max(1, ...fields.map((x: any) => (x.type ? NATURAL[x.type.replace(/^const\s+/, '')] ?? 1 : 1)));
      const unpadded = size !== null && size % widest !== 0;
      const packed = hexNum(data.alignment) === 1 || data.packed === true || misaligned || unpadded;
      if (packed) lines.push(`#pragma pack(push, 1) /* ${misaligned ? 'fields off their natural alignment' : unpadded ? 'declared size has no tail padding' : 'packed'}: offsets as documented */`);
      lines.push(`struct ${name} {`);
      let cursor = 0;
      let flexible = false;
      for (const [fieldIndex, field] of fields.entries()) {
        if (field.offset > cursor) {
          lines.push(`    uint8_t _pad_${cursor.toString(16).toUpperCase()}[0x${(field.offset - cursor).toString(16).toUpperCase()}];`);
        } else if (field.offset < cursor) {
          lines.push(`    /* overlapping field at 0x${field.offset.toString(16).toUpperCase()} skipped: ${comment(field.name)} */`);
          continue;
        }
        const fieldId = field.name || `field_${field.offset.toString(16).toUpperCase()}`;
        if (FN_POINTER.test(field.rawType.trim())) {
          // A function pointer: the name goes inside "(*)".
          lines.push(`    /* 0x${field.offset.toString(16).toUpperCase().padStart(2, '0')} */ ${field.rawType.trim().replace(/\(\s*\*\s*\)/, `(*${fieldId})`)};${field.notes ? ` /* ${comment(field.notes)} */` : ''}`);
          cursor = field.offset + (field.size ?? 4);
          continue;
        }
        // "int16_t[2][4]", "char[8]": typed arrays; a symbolic length ("[width]") stays bytes with a note.
        const array = /^(.*?)\s*((?:\[[^\]]*\])+)$/.exec(field.rawType.trim());
        const dims = array ? [...array[2].matchAll(/\[\s*([^\]]*?)\s*\]/g)].map((d) => d[1]) : [];
        const numericDims = dims.length > 0 && dims.every((d) => /^(?:0x[0-9a-f]+|\d+)$/i.test(d));
        let type = array ? cType(array[1]) : field.type;
        let note = field.notes;
        // The last field "T[]" or "T[count]" (Rich header entries, a trailing name): a flexible array member.
        const flex = array && dims.length === 1 && !numericDims && fieldIndex === fields.length - 1 && fields.length > 1 && !!type;
        if (flex && dims[0]) note = [`count: ${dims[0]}`, note].filter(Boolean).join('; ');
        if (array && !numericDims && !flex) { note = [`${field.rawType}`, note].filter(Boolean).join('; '); type = null; }
        const base = type ? baseType(type) : undefined;
        if (type && base && !BUILTIN.test(type) && !defined.has(base)) {
          if (type.includes('*')) forward.add(base);
          else if (!knownStructs.has(base) && (field.size === 4 || field.size === 8) && /(?:_ptr|Ptr|_p|_handle|HANDLE)$/.test(base) && !array) {
            // A pointer typedef from elsewhere (j_common_ptr, HANDLE): a pointer, so the next offsets stay right.
            note = [`${field.rawType} (a pointer typedef not defined here)`, note].filter(Boolean).join('; ');
            type = 'void *';
            unknownTypes.add(base);
          } else {
            // A type this header does not define, by value: its bytes, with the type named in a comment.
            note = [`${field.rawType} (${knownStructs.has(base) ? 'defined on another page' : 'type not defined here'})`, note].filter(Boolean).join('; ');
            if (!knownStructs.has(base)) unknownTypes.add(base);
            type = null;
          }
        }
        const suffix = type && flex ? '[]' : type && numericDims ? dims.map((d) => `[${d}]`).join('') : '';
        if (flex && type) flexible = true;
        const decl = type ? `${type} ${fieldId}${suffix};` : `uint8_t ${fieldId}[0x${(field.size ?? 1).toString(16).toUpperCase()}];`;
        lines.push(`    /* 0x${field.offset.toString(16).toUpperCase().padStart(2, '0')} */ ${decl}${note ? ` /* ${comment(note)} */` : ''}`);
        // Bit fields as comments under the field (C bit-field layout is not portable).
        for (const b of field.bits) lines.push(`    /*        bit ${comment(b?.bit)}: ${comment(b?.name)}${b?.notes ? ` (${comment(b.notes)})` : ''} */`);
        cursor = flex ? field.offset : field.offset + (field.size ?? (field.type ? 0 : 1));
      }
      if (size !== null && cursor > size) warnings.push(`${name}: the fields end at 0x${cursor.toString(16).toUpperCase()}, past the declared size 0x${size.toString(16).toUpperCase()}.`);
      if (flexible && size !== null && size !== cursor) {
        lines.push(`    /* declared size 0x${size.toString(16).toUpperCase()}; the flexible array starts at 0x${cursor.toString(16).toUpperCase()} */`);
        warnings.push(`${name}: declared size 0x${size.toString(16).toUpperCase()}, but the flexible array starts at 0x${cursor.toString(16).toUpperCase()} (size is the fixed part, or "variable").`);
      }
      if (size !== null && size > cursor && !flexible) lines.push(`    uint8_t _pad_${cursor.toString(16).toUpperCase()}[0x${(size - cursor).toString(16).toUpperCase()}];`);
      if (floating.length) {
        // C has no field at "16+n": the fields after a variable-length one, as documented.
        lines.push(`    /* then, after the variable-length part: ${floating.map((x: any) => `${comment(x.name || '?')} (${comment(x.rawType || '?')}) at ${comment(String(x.rawOffset ?? '?'))}`).join('; ')} */`);
        warnings.push(`${name}: ${floating.length} field(s) with offsets that are not numbers (${floating.map((x: any) => comment(x.name || '?')).join(', ')}) are comments at the end of the struct.`);
      }
      lines.push(`};${size !== null ? ` /* size 0x${size.toString(16).toUpperCase()} */` : data.size === 'variable' ? ' /* variable size */' : ''}`);
      if (packed) lines.push('#pragma pack(pop)');
      lines.push('');
    } else if (f.kind === 'enum') {
      const name = ident(fieldName(data.name).name.replace(/_+$/, ''), 'UnnamedEnum');
      lines.push(`typedef enum ${name} {`);
      const values = enumValues(data.values).map((v) => ({ ...v, named: fieldName(v.name) }));
      // Enum constants share one C namespace: when any constant of this enum is already used (NONE, OP_MOVE
      // in two opcode tables), all of its constants get the enum's name in front, so the names stay regular.
      const prefixAll = values.some((v) => enumConstants.has(ident(v.named.name, 'VALUE')) || defined.has(ident(v.named.name, 'VALUE')));
      for (const v of values) {
        // "MF_SPECIAL (multiplayer only)": the identifier, and the rest as a comment.
        const named = v.named;
        const literal = v.value === null ? '' : ` = ${enumLiteral(v.value)}`;
        let id = prefixAll ? ident(`${name}_${named.name}`, 'VALUE') : ident(named.name, 'VALUE');
        for (let n = 2; enumConstants.has(id); n++) id = `${ident(`${name}_${named.name}`, 'VALUE')}_${n}`;
        enumConstants.add(id);
        // A range: the constant is its first value, the range in the comment.
        const notes = [v.end !== undefined && v.value !== null ? `${enumLiteral(v.value)}-${enumLiteral(v.end)}` : '', named.rest, v.notes].filter(Boolean).join('; ');
        lines.push(`    ${id}${literal},${notes ? ` /* ${comment(notes)} */` : ''}`);
      }
      lines.push(`} ${name};`, '');
    } else if (f.kind === 'vtable') {
      const name = ident(`${data.class}_vtbl`, 'Unnamed_vtbl');
      lines.push(`struct ${name} {`);
      (Array.isArray(data.slots) ? data.slots : []).forEach((slot: any, i: number) => {
        lines.push(`    void *${ident(slot.name ?? slot, `slot_${i}`)}; /* slot ${i} */`);
      });
      lines.push(`};`, '');
    } else {
      skipped.push(f.title);
    }
  }
  // Fixed hardware addresses of a platform (I/O registers, vectors): one #define each.
  const hardware = s.index.factsForSubject(subject).filter((f) => f.status !== 'rejected').flatMap((f) => {
    const d = JSON.parse(f.data);
    const address = d.address?.kind === 'hardware' ? hexNum(d.address.value) : null;
    return address === null ? [] : [{ name: ident(d.name, ''), address, status: f.status, title: f.title, type: cType(d.type) }];
  }).filter((h) => h.name).sort((a, b) => a.address - b.address);
  if (hardware.length) {
    lines.push('/* Hardware addresses (the same in every program on this platform) */');
    for (const h of hardware) {
      const hex = `0x${h.address.toString(16).toUpperCase()}`;
      // A register block typed by a struct defined above: a pointer to it (VI_REGS->origin).
      // Single registers stay plain addresses, as hardware headers usually give them.
      const base = h.type && !h.type.includes('*') ? baseType(h.type) : undefined;
      const typed = h.type && base && !BUILTIN.test(h.type) && defined.has(base);
      lines.push(typed
        ? `#define ${h.name} ((volatile ${h.type} *)${hex}) /* [${h.status}] ${comment(h.title)} */`
        : `#define ${h.name} ${hex} /* [${h.status}] ${comment(h.title)}${h.type ? `; type ${comment(h.type)}` : ''} */`);
    }
    lines.push('');
  }
  if (!facts.length && !hardware.length) lines.push('/* No struct, enum or vtable facts for this subject yet. Add them with add_fact. */');
  // Pointers to types from other pages: forward declarations right after the includes.
  const elsewhere = [...forward].filter((t) => !defined.has(t));
  const at = lines.indexOf('#include <stdint.h>') + 2;
  if (elsewhere.length) lines.splice(at, 0, ...elsewhere.map((t) => `typedef struct ${t} ${t}; /* ${knownStructs.has(t) ? 'defined on another page' : 'not defined by any fact: declared so pointers to it compile'} */`), '');
  if (unknownTypes.size) warnings.push(`Types not defined by any fact: ${[...unknownTypes].join(', ')}. Fields of these types are bytes (or void * for pointer typedefs); add struct facts for them, or write the field as a stdint type.`);
  return { subject, build, facts: facts.length, warnings: warnings.length ? warnings : undefined, header: lines.join('\n') };
}

