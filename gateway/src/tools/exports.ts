/**
 * export_header / export_symbols: turn facts into artifacts other agents can
 * import directly (C headers, Ghidra/IDA scripts). Every value that reaches
 * generated code is sanitized: names become identifiers, text becomes JSON
 * string literals in comments-free positions.
 */
import type { Services } from './context.ts';
import { ToolError } from './context.ts';
import { normalizeTitle, requireTitle, SUBJECT_TYPES, TitleError, type PageType } from '../wiki/titles.ts';

const HEADER_NOTE = 'Generated by ReverseEngineering.wiki from community facts. Facts marked "claimed" are unverified. Generated code: MIT-0.';

function ident(raw: unknown, fallback: string): string {
  const s = String(raw ?? '').replace(/[^A-Za-z0-9_]/g, '_').replace(/^(\d)/, '_$1').slice(0, 120);
  return s && /[A-Za-z_]/.test(s) ? s : fallback;
}

function qualifiedName(raw: unknown, fallback: string): string {
  // Allows C++ scopes (Foo::Bar) for symbol names in disassemblers.
  const s = String(raw ?? '').replace(/[^A-Za-z0-9_:~<>]/g, '_').slice(0, 200);
  return s && /[A-Za-z_]/.test(s) ? s : fallback;
}

function comment(text: unknown): string {
  return String(text ?? '').replace(/[^\x20-\x7e]/g, '?').replace(/\*\//g, '* /').slice(0, 160);
}

function hexNum(raw: unknown): number | null {
  if (typeof raw === 'number' && Number.isFinite(raw)) return raw;
  if (typeof raw === 'string' && /^0x[0-9a-f]+$/i.test(raw.trim())) return parseInt(raw.trim(), 16);
  if (typeof raw === 'string' && /^\d+$/.test(raw.trim())) return parseInt(raw.trim(), 10);
  return null;
}

const C_TYPE = /^(?:const\s+)?(?:unsigned\s+|signed\s+)?[A-Za-z_][\w]*(?:\s*\*+)?$/;

function cType(raw: unknown): string | null {
  const s = String(raw ?? '').trim();
  return C_TYPE.test(s) ? s : null;
}

let sIndex: Services['index'] | undefined;

function cleanTitle(raw: string, allowed: readonly PageType[]): string {
  try {
    return requireTitle(raw, allowed, (t) => !!sIndex?.page(t));
  } catch (error) {
    if (error instanceof TitleError) throw new ToolError('BAD_TITLE', error.message);
    throw error;
  }
}

export function exportHeader(s: Services, args: { subject: string; build?: string }) {
  sIndex = s.index;
  const subject = s.index.resolveRedirect(cleanTitle(args.subject, SUBJECT_TYPES));
  const build = args.build ? normalizeTitle(args.build) : null;
  const facts = s.index.factsForSubject(subject, ['struct', 'enum', 'vtable'])
    .filter((f) => !build || f.level !== 'build' || f.applies_to === build)
    .filter((f) => f.status !== 'rejected');
  const lines = [`/* ${HEADER_NOTE}`, ` * Subject: ${comment(subject)}${build ? `\n * Build: ${comment(build)}` : ''}`,
    ` * Generated: ${new Date().toISOString()} */`, '#pragma once', '#include <stdint.h>', ''];
  const skipped: string[] = [];
  for (const f of facts) {
    const data = JSON.parse(f.data);
    lines.push(`/* [${f.status}] ${comment(f.title)} */`);
    if (f.kind === 'struct') {
      const name = ident(data.name, 'UnnamedStruct');
      const size = hexNum(data.size);
      const fields = (Array.isArray(data.fields) ? data.fields : [])
        .map((x: any) => ({ offset: hexNum(x.offset), size: hexNum(x.size), type: cType(x.type), name: ident(x.name, ''), notes: x.notes }))
        .filter((x: any) => x.offset !== null)
        .sort((a: any, b: any) => a.offset - b.offset);
      lines.push(`typedef struct ${name} {`);
      let cursor = 0;
      for (const field of fields) {
        if (field.offset > cursor) {
          lines.push(`    uint8_t _pad_${cursor.toString(16).toUpperCase()}[0x${(field.offset - cursor).toString(16).toUpperCase()}];`);
        } else if (field.offset < cursor) {
          lines.push(`    /* overlapping field at 0x${field.offset.toString(16).toUpperCase()} skipped: ${comment(field.name)} */`);
          continue;
        }
        const fieldName = field.name || `field_${field.offset.toString(16).toUpperCase()}`;
        const decl = field.type ? `${field.type} ${fieldName};` : `uint8_t ${fieldName}[0x${(field.size ?? 1).toString(16).toUpperCase()}];`;
        lines.push(`    /* 0x${field.offset.toString(16).toUpperCase().padStart(2, '0')} */ ${decl}${field.notes ? ` /* ${comment(field.notes)} */` : ''}`);
        cursor = field.offset + (field.size ?? (field.type ? 0 : 1));
      }
      if (size !== null && size > cursor) lines.push(`    uint8_t _pad_${cursor.toString(16).toUpperCase()}[0x${(size - cursor).toString(16).toUpperCase()}];`);
      lines.push(`} ${name};${size !== null ? ` /* size 0x${size.toString(16).toUpperCase()} */` : ''}`, '');
    } else if (f.kind === 'enum') {
      const name = ident(data.name, 'UnnamedEnum');
      lines.push(`typedef enum ${name} {`);
      for (const v of Array.isArray(data.values) ? data.values : []) {
        const value = hexNum(v.value);
        lines.push(`    ${ident(v.name, 'VALUE')}${value !== null ? ` = 0x${value.toString(16).toUpperCase()}` : ''},`);
      }
      lines.push(`} ${name};`, '');
    } else if (f.kind === 'vtable') {
      const name = ident(`${data.class}_vtbl`, 'Unnamed_vtbl');
      lines.push(`typedef struct ${name} {`);
      (Array.isArray(data.slots) ? data.slots : []).forEach((slot: any, i: number) => {
        lines.push(`    void *${ident(slot.name ?? slot, `slot_${i}`)}; /* slot ${i} */`);
      });
      lines.push(`} ${name};`, '');
    } else {
      skipped.push(f.title);
    }
  }
  if (!facts.length) lines.push('/* No struct, enum or vtable facts for this subject yet. Add them with add_fact. */');
  return { subject, build, facts: facts.length, header: lines.join('\n') };
}

export function exportSymbols(s: Services, args: { build: string; tool: 'ghidra' | 'ida' | 'json' }) {
  const build = cleanTitle(args.build, ['build']);
  if (!s.index.page(build)) throw new ToolError('NOT_FOUND', `"${build}" is not a known build. Use lookup_binary or register_build.`);
  const rows = s.index.factsForBuild(build).filter((f) => ['function', 'global', 'vtable'].includes(f.kind) && f.status !== 'rejected');
  const symbols: Array<{ rva: number; name: string; kind: string; status: string; fact: string }> = [];
  const signatureOnly: Array<{ name: string; pattern: string; fact: string }> = [];
  const otherAddresses: Array<{ name: string; kind: string; value: string; fact: string }> = [];
  for (const f of rows) {
    const data = JSON.parse(f.data);
    const rva = hexNum(data.rva);
    const name = qualifiedName(data.name ?? data.class, `rewiki_${f.kind}`);
    if (rva !== null) symbols.push({ rva, name, kind: f.kind, status: f.status, fact: f.title });
    else if (data.address && typeof data.address.value === 'string') otherAddresses.push({ name, kind: String(data.address.kind), value: data.address.value, fact: f.title });
    else if (typeof data.signature === 'string') signatureOnly.push({ name, pattern: data.signature, fact: f.title });
  }
  // The build's symbol map fills in every address no fact covers (facts win: they carry evidence).
  const byFact = new Set(symbols.map((x) => x.rva));
  let fromMap = 0;
  for (const m of s.index.symbolsForBuild(build)) {
    if (byFact.has(m.rva) || (m.kind !== 'function' && m.kind !== 'global' && m.kind !== 'vtable' && m.kind !== 'label')) continue;
    symbols.push({ rva: m.rva, name: qualifiedName(m.name, `rewiki_${m.kind}`), kind: m.kind === 'label' ? 'global' : m.kind, status: `map:${m.confidence}`, fact: m.title });
    fromMap++;
  }
  symbols.sort((a, b) => a.rva - b.rva);
  const ascii = (x: string) => JSON.stringify(x.replace(/[^\x20-\x7e]/g, '?'));
  const pyList = symbols.map((x) => `    (0x${x.rva.toString(16)}, ${ascii(x.name)}, ${ascii(x.kind)}, ${ascii(x.status)}, ${ascii(x.fact)}),`).join('\n');
  const pySigs = [
    ...signatureOnly.map((x) => `#   ${comment(x.name)}: pattern ${comment(x.pattern)}  (${comment(x.fact)})`),
    ...otherAddresses.map((x) => `#   ${comment(x.name)}: ${comment(x.kind)} address ${comment(x.value)}  (${comment(x.fact)})`),
  ].join('\n');
  const head = `# ${HEADER_NOTE}\n# Build: ${comment(build)}\n# Generated: ${new Date().toISOString()}\n`;

  let script: string;
  if (args.tool === 'json') {
    script = JSON.stringify({ build, symbols, signature_only: signatureOnly, other_addresses: otherAddresses }, null, 2);
  } else if (args.tool === 'ghidra') {
    script = `${head}# Run in Ghidra's Script Manager (Jython or PyGhidra) with the program open.
from ghidra.program.model.symbol import SourceType

SYMBOLS = [
${pyList}
]

base = currentProgram.getImageBase()
for rva, name, kind, status, fact in SYMBOLS:
    addr = base.add(rva)
    if kind == "function" and getFunctionAt(addr) is None:
        createFunction(addr, name)
    createLabel(addr, name, True, SourceType.USER_DEFINED)
    setPlateComment(addr, "ReverseEngineering.wiki [%s] %s" % (status, fact))
print("ReverseEngineering.wiki: applied %d symbols" % len(SYMBOLS))
${pySigs ? `\n# Not applied automatically (signature only, or a non-RVA address: segmented, banked, va, file offset):\n${pySigs}\n` : ''}`;
  } else {
    script = `${head}# Run in IDA via File > Script file (IDAPython).
import idaapi, idc, ida_funcs, ida_name

SYMBOLS = [
${pyList}
]

base = idaapi.get_imagebase()
for rva, name, kind, status, fact in SYMBOLS:
    ea = base + rva
    if kind == "function":
        ida_funcs.add_func(ea)
    ida_name.set_name(ea, name, ida_name.SN_NOWARN | ida_name.SN_NOCHECK | ida_name.SN_FORCE)
    idc.set_cmt(ea, "ReverseEngineering.wiki [%s] %s" % (status, fact), 1)
print("ReverseEngineering.wiki: applied %d symbols" % len(SYMBOLS))
${pySigs ? `\n# Not applied automatically (signature only, or a non-RVA address: segmented, banked, va, file offset):\n${pySigs}\n` : ''}`;
  }
  return {
    build, tool: args.tool, symbols: symbols.length, from_facts: symbols.length - fromMap, from_symbol_map: fromMap, signature_only: signatureOnly.length, other_addresses: otherAddresses.length, script,
    warning: 'Review generated scripts before running. Names come from community facts (status claimed/verified) and the symbol map (status map:<confidence>).',
  };
}
