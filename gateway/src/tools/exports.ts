/**
 * export_header / export_symbols: turn facts into artifacts other agents can
 * import directly (C headers, Ghidra/IDA scripts). Every value that reaches
 * generated code is sanitized: names become identifiers, text becomes JSON
 * string literals in comments-free positions.
 */
import type { Services } from './context.ts';
import { ToolError } from './context.ts';
import { normalizeTitle, requireTitle, SUBJECT_TYPES, TitleError, type PageType } from '../wiki/titles.ts';

const HEADER_NOTE = 'Generated by ReverseEngineering.wiki from community facts. Facts marked "claimed" are unverified. Generated code: MIT-0.';

function ident(raw: unknown, fallback: string): string {
  const s = String(raw ?? '').replace(/[^A-Za-z0-9_]/g, '_').replace(/^(\d)/, '_$1').slice(0, 120);
  return s && /[A-Za-z_]/.test(s) ? s : fallback;
}

function qualifiedName(raw: unknown, fallback: string): string {
  // Allows C++ scopes (Foo::Bar) for symbol names in disassemblers.
  const s = String(raw ?? '').replace(/[^A-Za-z0-9_:~<>]/g, '_').slice(0, 200);
  return s && /[A-Za-z_]/.test(s) ? s : fallback;
}

function comment(text: unknown): string {
  return String(text ?? '').replace(/[^\x20-\x7e]/g, '?').replace(/\*\//g, '* /').slice(0, 160);
}

function hexNum(raw: unknown): number | null {
  if (typeof raw === 'number' && Number.isFinite(raw)) return raw;
  if (typeof raw === 'string' && /^0x[0-9a-f]+$/i.test(raw.trim())) return parseInt(raw.trim(), 16);
  if (typeof raw === 'string' && /^\d+$/.test(raw.trim())) return parseInt(raw.trim(), 10);
  return null;
}

const C_TYPE = /^(?:const\s+)?(?:(?:struct|enum|union)\s+)?(?:unsigned\s+|signed\s+)?[A-Za-z_][\w]*(?:\s*\*+)?$/;
/** "void (*)(void)", "int (*)(Entity *, int)": a function pointer type. */
const FN_POINTER = /^[A-Za-z_][\w\s*]*\(\s*\*\s*\)\s*\([\w\s*,.]*\)$/;

/** The type name a field uses by value or through a pointer ("struct Entity *" → Entity). */
function baseType(type: string): string {
  return type.replace(/^const\s+/, '').replace(/^(?:struct|enum|union)\s+/, '').replace(/\s*\*+$/, '').trim();
}

/**
 * Structs in an order C accepts: one used by value comes before the struct that contains it.
 * (Pointers are fine in any order: every struct also gets a forward declaration.)
 */
function dependencyOrder<T extends { kind: string; data: string }>(facts: T[], name: (f: T) => string): T[] {
  const structs = facts.filter((f) => f.kind === 'struct');
  const byName = new Map(structs.map((f) => [name(f), f]));
  const out: T[] = [];
  const state = new Map<string, 'visiting' | 'done'>();
  const visit = (f: T) => {
    const n = name(f);
    if (state.get(n)) return;
    state.set(n, 'visiting');
    for (const field of JSON.parse(f.data).fields ?? []) {
      const t = String(field?.type ?? '');
      if (t.includes('*')) continue;
      const dep = byName.get(baseType(t.replace(/\[.*$/, '')));
      if (dep && state.get(name(dep)) !== 'visiting') visit(dep);
    }
    state.set(n, 'done');
    out.push(f);
  };
  for (const f of structs) visit(f);
  return [...facts.filter((f) => f.kind === 'enum'), ...out, ...facts.filter((f) => f.kind !== 'enum' && f.kind !== 'struct')];
}
const BUILTIN = /^(?:const\s+)?(?:unsigned\s+|signed\s+)?(?:u?int(?:8|16|32|64)_t|u?intptr_t|size_t|char|short|int|long|long long|float|double|void|bool|_Bool|wchar_t|BYTE|WORD|DWORD|QWORD|BOOL)\b/;

/** A field name that is a description ("type (0 = saved game)"): a short identifier, the rest as a comment. */
function fieldName(raw: unknown): { name: string; rest?: string } {
  const text = String(raw ?? '').trim();
  if (/^[A-Za-z_]\w*$/.test(text)) return { name: text };
  // "64GB_LINK_CABLE": an identifier but for the leading digit; keep it whole.
  if (/^\d\w*$/.test(text)) return { name: `_${text}` };
  const first = /[A-Za-z_]\w*/.exec(text)?.[0] ?? '';
  return { name: ident(first, ''), rest: text };
}

function cType(raw: unknown): string | null {
  const s = String(raw ?? '').trim();
  return C_TYPE.test(s) ? s : null;
}

/**
 * Enum values as agents write them: {"0": "Rifle"} (the documented form), {"Rifle": 0},
 * [{name, value}] or ["Rifle", "Shotgun"].
 */
/** Enum values may be negative ("-1", -14): hexNum only reads unsigned numbers. */
function signedNum(raw: unknown): number | null {
  if (typeof raw === 'number' && Number.isInteger(raw)) return raw;
  if (typeof raw === 'string' && /^-\d+$/.test(raw.trim())) return parseInt(raw.trim(), 10);
  // Character codes ("'A'", as mangling letters and opcodes are often written).
  if (typeof raw === 'string' && /^'[\x20-\x7e]'$/.test(raw.trim())) return raw.trim().charCodeAt(1);
  return hexNum(raw);
}

function enumValues(raw: unknown): Array<{ name: string; value: number | null }> {
  if (Array.isArray(raw)) {
    return raw.map((v, i) => (typeof v === 'string' ? { name: v, value: i } : { name: String(v?.name ?? ''), value: signedNum(v?.value) }));
  }
  if (raw && typeof raw === 'object') {
    return Object.entries(raw as Record<string, unknown>).map(([k, v]) => {
      const keyNumber = signedNum(k);
      if (keyNumber !== null && typeof v === 'string') return { name: v, value: keyNumber };
      const valueNumber = signedNum(v);
      if (valueNumber !== null) return { name: k, value: valueNumber };
      return { name: k, value: null };
    }).sort((a, b) => (a.value ?? 0) - (b.value ?? 0));
  }
  return [];
}

let sIndex: Services['index'] | undefined;

function cleanTitle(raw: string, allowed: readonly PageType[]): string {
  try {
    return requireTitle(raw, allowed, (t) => !!sIndex?.page(t));
  } catch (error) {
    if (error instanceof TitleError) throw new ToolError('BAD_TITLE', error.message);
    throw error;
  }
}

export function exportHeader(s: Services, args: { subject: string; build?: string }) {
  sIndex = s.index;
  const subject = s.index.resolveRedirect(cleanTitle(args.subject, SUBJECT_TYPES));
  const build = args.build ? normalizeTitle(args.build) : null;
  const facts = s.index.factsForSubject(subject, ['struct', 'enum', 'vtable'])
    .filter((f) => !build || f.level !== 'build' || f.applies_to === build)
    .filter((f) => f.status !== 'rejected');
  const lines = [`/* ${HEADER_NOTE}`, ` * Subject: ${comment(subject)}${build ? `\n * Build: ${comment(build)}` : ''}`,
    ` * Generated: ${new Date().toISOString()} */`, '#pragma once', '#include <stdint.h>', ''];
  const skipped: string[] = [];
  // Types defined in this header; others come from other pages and must still compile here.
  const typeName = (f: { kind: string; data: string }) => {
    try {
      const d = JSON.parse(f.data);
      return f.kind === 'vtable' ? ident(`${d.class}_vtbl`, '') : ident(fieldName(d.name).name, '');
    } catch {
      return '';
    }
  };
  const defined = new Set(facts.map(typeName));
  const forward = new Set<string>();
  const enumConstants = new Set<string>();
  // Every struct is declared first, so pointers between them work in any order.
  const declared = facts.filter((f) => f.kind !== 'enum').map(typeName).filter(Boolean);
  if (declared.length) lines.push(...declared.map((t) => `typedef struct ${t} ${t};`), '');
  for (const f of dependencyOrder(facts, typeName)) {
    const data = JSON.parse(f.data);
    lines.push(`/* [${f.status}] ${comment(f.title)} */`);
    if (f.kind === 'struct') {
      const name = ident(fieldName(data.name).name, 'UnnamedStruct');
      const size = hexNum(data.size);
      const fields = (Array.isArray(data.fields) ? data.fields : [])
        .map((x: any) => {
          const named = fieldName(x.name);
          return { offset: hexNum(x.offset), size: hexNum(x.size), type: cType(x.type), rawType: String(x.type ?? ''), name: named.name, notes: [named.rest, x.notes].filter(Boolean).join('; '), bits: Array.isArray(x.bits) ? x.bits : [] };
        })
        .filter((x: any) => x.offset !== null)
        .sort((a: any, b: any) => a.offset - b.offset);
      const NATURAL: Record<string, number> = { int16_t: 2, uint16_t: 2, int32_t: 4, uint32_t: 4, float: 4, int64_t: 8, uint64_t: 8, double: 8 };
      const misaligned = fields.some((x: any) => {
        const n = x.type ? NATURAL[x.type.replace(/^const\s+/, '')] : undefined;
        return n !== undefined && x.offset % n !== 0;
      });
      const packed = hexNum(data.alignment) === 1 || data.packed === true || misaligned;
      if (packed) lines.push(`#pragma pack(push, 1) /* ${misaligned ? 'fields off their natural alignment' : 'packed'}: offsets as documented */`);
      lines.push(`struct ${name} {`);
      let cursor = 0;
      for (const field of fields) {
        if (field.offset > cursor) {
          lines.push(`    uint8_t _pad_${cursor.toString(16).toUpperCase()}[0x${(field.offset - cursor).toString(16).toUpperCase()}];`);
        } else if (field.offset < cursor) {
          lines.push(`    /* overlapping field at 0x${field.offset.toString(16).toUpperCase()} skipped: ${comment(field.name)} */`);
          continue;
        }
        const fieldId = field.name || `field_${field.offset.toString(16).toUpperCase()}`;
        if (FN_POINTER.test(field.rawType.trim())) {
          // A function pointer: the name goes inside "(*)".
          lines.push(`    /* 0x${field.offset.toString(16).toUpperCase().padStart(2, '0')} */ ${field.rawType.trim().replace(/\(\s*\*\s*\)/, `(*${fieldId})`)};${field.notes ? ` /* ${comment(field.notes)} */` : ''}`);
          cursor = field.offset + (field.size ?? 4);
          continue;
        }
        // "int16_t[2][4]", "char[8]": typed arrays; a symbolic length ("[width]") stays bytes with a note.
        const array = /^(.*?)\s*((?:\[[^\]]*\])+)$/.exec(field.rawType.trim());
        const dims = array ? [...array[2].matchAll(/\[\s*([^\]]*?)\s*\]/g)].map((d) => d[1]) : [];
        const numericDims = dims.length > 0 && dims.every((d) => /^(?:0x[0-9a-f]+|\d+)$/i.test(d));
        let type = array ? cType(array[1]) : field.type;
        let note = field.notes;
        if (array && !numericDims) { note = [`${field.rawType}`, note].filter(Boolean).join('; '); type = null; }
        const base = type ? baseType(type) : undefined;
        if (type && base && !BUILTIN.test(type) && !defined.has(base)) {
          if (type.includes('*')) forward.add(base);
          else {
            // A type from another page, by value: its bytes, with the type named in a comment.
            note = [`${field.rawType} (defined on another page)`, note].filter(Boolean).join('; ');
            type = null;
          }
        }
        const suffix = type && numericDims ? dims.map((d) => `[${d}]`).join('') : '';
        const decl = type ? `${type} ${fieldId}${suffix};` : `uint8_t ${fieldId}[0x${(field.size ?? 1).toString(16).toUpperCase()}];`;
        lines.push(`    /* 0x${field.offset.toString(16).toUpperCase().padStart(2, '0')} */ ${decl}${note ? ` /* ${comment(note)} */` : ''}`);
        // Bit fields as comments under the field (C bit-field layout is not portable).
        for (const b of field.bits) lines.push(`    /*        bit ${comment(b?.bit)}: ${comment(b?.name)}${b?.notes ? ` (${comment(b.notes)})` : ''} */`);
        cursor = field.offset + (field.size ?? (field.type ? 0 : 1));
      }
      if (size !== null && size > cursor) lines.push(`    uint8_t _pad_${cursor.toString(16).toUpperCase()}[0x${(size - cursor).toString(16).toUpperCase()}];`);
      lines.push(`};${size !== null ? ` /* size 0x${size.toString(16).toUpperCase()} */` : data.size === 'variable' ? ' /* variable size */' : ''}`);
      if (packed) lines.push('#pragma pack(pop)');
      lines.push('');
    } else if (f.kind === 'enum') {
      const name = ident(fieldName(data.name).name.replace(/_+$/, ''), 'UnnamedEnum');
      lines.push(`typedef enum ${name} {`);
      const values = enumValues(data.values).map((v) => ({ ...v, named: fieldName(v.name) }));
      // Enum constants share one C namespace: when any constant of this enum is already used (NONE, OP_MOVE
      // in two opcode tables), all of its constants get the enum's name in front, so the names stay regular.
      const prefixAll = values.some((v) => enumConstants.has(ident(v.named.name, 'VALUE')));
      for (const v of values) {
        // "MF_SPECIAL (multiplayer only)": the identifier, and the rest as a comment.
        const named = v.named;
        const literal = v.value === null ? '' : v.value < 0 ? ` = ${v.value}` : ` = 0x${v.value.toString(16).toUpperCase()}`;
        let id = prefixAll ? ident(`${name}_${named.name}`, 'VALUE') : ident(named.name, 'VALUE');
        for (let n = 2; enumConstants.has(id); n++) id = `${ident(`${name}_${named.name}`, 'VALUE')}_${n}`;
        enumConstants.add(id);
        lines.push(`    ${id}${literal},${named.rest ? ` /* ${comment(named.rest)} */` : ''}`);
      }
      lines.push(`} ${name};`, '');
    } else if (f.kind === 'vtable') {
      const name = ident(`${data.class}_vtbl`, 'Unnamed_vtbl');
      lines.push(`struct ${name} {`);
      (Array.isArray(data.slots) ? data.slots : []).forEach((slot: any, i: number) => {
        lines.push(`    void *${ident(slot.name ?? slot, `slot_${i}`)}; /* slot ${i} */`);
      });
      lines.push(`};`, '');
    } else {
      skipped.push(f.title);
    }
  }
  // Fixed hardware addresses of a platform (I/O registers, vectors): one #define each.
  const hardware = s.index.factsForSubject(subject).filter((f) => f.status !== 'rejected').flatMap((f) => {
    const d = JSON.parse(f.data);
    const address = d.address?.kind === 'hardware' ? hexNum(d.address.value) : null;
    return address === null ? [] : [{ name: ident(d.name, ''), address, status: f.status, title: f.title, type: cType(d.type) }];
  }).filter((h) => h.name).sort((a, b) => a.address - b.address);
  if (hardware.length) {
    lines.push('/* Hardware addresses (the same in every program on this platform) */');
    for (const h of hardware) {
      const hex = `0x${h.address.toString(16).toUpperCase()}`;
      // A register block typed by a struct defined above: a pointer to it (VI_REGS->origin).
      // Single registers stay plain addresses, as hardware headers usually give them.
      const base = h.type && !h.type.includes('*') ? baseType(h.type) : undefined;
      const typed = h.type && base && !BUILTIN.test(h.type) && defined.has(base);
      lines.push(typed
        ? `#define ${h.name} ((volatile ${h.type} *)${hex}) /* [${h.status}] ${comment(h.title)} */`
        : `#define ${h.name} ${hex} /* [${h.status}] ${comment(h.title)}${h.type ? `; type ${comment(h.type)}` : ''} */`);
    }
    lines.push('');
  }
  if (!facts.length && !hardware.length) lines.push('/* No struct, enum or vtable facts for this subject yet. Add them with add_fact. */');
  // Pointers to types from other pages: forward declarations right after the includes.
  const elsewhere = [...forward].filter((t) => !defined.has(t));
  if (elsewhere.length) lines.splice(6, 0, ...elsewhere.map((t) => `typedef struct ${t} ${t}; /* defined on another page */`), '');
  return { subject, build, facts: facts.length, header: lines.join('\n') };
}

type SymbolTool = 'ghidra' | 'ida' | 'json' | 'sym';

/** A platform's fixed hardware addresses (memory-mapped I/O, vectors, BIOS calls), for every program on it. */
function exportPlatformSymbols(s: Services, args: { platform: string; tool: SymbolTool }) {
  const platform = s.index.resolveRedirect(cleanTitle(args.platform, ['platform']));
  if (!s.index.page(platform)) throw new ToolError('NOT_FOUND', `"${platform}" does not exist.`);
  const symbols: Array<{ address: number; name: string; kind: string; status: string; fact: string }> = [];
  for (const f of s.index.factsForSubject(platform).filter((x) => x.status !== 'rejected')) {
    const data = JSON.parse(f.data);
    if (data.address?.kind !== 'hardware') continue;
    const address = hexNum(data.address.value);
    if (address !== null) symbols.push({ address, name: qualifiedName(data.name ?? data.class ?? f.title.split('/').pop()?.trim(), `rewiki_${f.kind}`), kind: f.kind, status: f.status, fact: f.title });
  }
  symbols.sort((a, b) => a.address - b.address);
  const ascii = (x: string) => JSON.stringify(x.replace(/[^\x20-\x7e]/g, '?'));
  const pyList = symbols.map((x) => `    (0x${x.address.toString(16)}, ${ascii(x.name)}, ${ascii(x.kind)}, ${ascii(x.status)}, ${ascii(x.fact)}),`).join('\n');
  const head = `# ${HEADER_NOTE}\n# Platform hardware: ${comment(platform)}\n# Generated: ${new Date().toISOString()}\n`;
  let script: string;
  if (args.tool === 'json') script = JSON.stringify({ platform, symbols }, null, 2);
  else if (args.tool === 'sym') script = `; ${HEADER_NOTE}\n; Platform hardware: ${comment(platform)}\n${symbols.map((x) => `00:${x.address.toString(16).toUpperCase().padStart(4, '0')} ${x.name}`).join('\n')}\n`;
  else if (args.tool === 'ghidra') {
    script = `${head}# Run in Ghidra's Script Manager (Jython or PyGhidra) with the program open. Absolute addresses.
from ghidra.program.model.symbol import SourceType

SYMBOLS = [
${pyList}
]

applied, unmapped = 0, []
for address, name, kind, status, fact in SYMBOLS:
    addr = toAddr(address)
    if currentProgram.getMemory().getBlock(addr) is None:
        unmapped.append("0x%x %s" % (address, name))
        continue
    createLabel(addr, name, True, SourceType.USER_DEFINED)
    setEOLComment(addr, "ReverseEngineering.wiki [%s] %s" % (status, fact))
    applied += 1
print("ReverseEngineering.wiki: applied %d hardware names" % applied)
if unmapped:
    print("No memory block at %d addresses (add one, e.g. uninitialized, to name them): %s" % (len(unmapped), ", ".join(unmapped)))
`;
  } else {
    script = `${head}# Run in IDA via File > Script file (IDAPython). Absolute addresses.
import idc, ida_name, ida_bytes

SYMBOLS = [
${pyList}
]

applied, unmapped = 0, []
for ea, name, kind, status, fact in SYMBOLS:
    if not ida_bytes.is_mapped(ea):
        unmapped.append("0x%x %s" % (ea, name))
        continue
    ida_name.set_name(ea, name, ida_name.SN_NOWARN | ida_name.SN_NOCHECK | ida_name.SN_FORCE)
    idc.set_cmt(ea, "ReverseEngineering.wiki [%s] %s" % (status, fact), 1)
    applied += 1
print("ReverseEngineering.wiki: applied %d hardware names" % applied)
if unmapped:
    print("No segment at %d addresses (add one to name them): %s" % (len(unmapped), ", ".join(unmapped)))
`;
  }
  return {
    platform, tool: args.tool, symbols: symbols.length, script,
    hint: symbols.length ? undefined : 'No hardware address facts on this platform yet: add_fact with data.address {kind: "hardware", value} at scope.level platform.',
    warning: 'Review generated scripts before running. Names come from community facts (status claimed/verified).',
  };
}

/**
 * Signature facts of a subject as a script that scans the user's own binary: each pattern found
 * exactly once gets its name. Knowledge from source releases and other builds applies to any build.
 */
function exportSignatureScan(s: Services, args: { subject: string; tool: SymbolTool }) {
  const subject = s.index.resolveRedirect(cleanTitle(args.subject, SUBJECT_TYPES));
  if (!s.index.page(subject)) throw new ToolError('NOT_FOUND', `"${subject}" does not exist.`);
  const sigs: Array<{ name: string; pattern: string; kind: string; status: string; fact: string; prototype?: string; offset: number; multiple: boolean }> = [];
  for (const f of s.index.factsForSubject(subject).filter((x) => x.status !== 'rejected')) {
    const d = JSON.parse(f.data);
    const pattern = typeof d.signature === 'string' ? d.signature : typeof d.pattern === 'string' ? d.pattern : null;
    if (!pattern || !/^(?:[0-9A-Fa-f]{2}|\?\??)(?:\s+(?:[0-9A-Fa-f]{2}|\?\??))+$/.test(pattern.trim())) continue;
    // The name goes at match start + offset: signature_offset (function/global), or offset of a signature fact; negative = before.
    const raw = d.signature_offset ?? (f.kind === 'signature' ? d.offset : undefined);
    const offset = typeof raw === 'string' && /^-/.test(raw.trim()) ? -(hexNum(raw.trim().slice(1)) ?? 0) : hexNum(raw) ?? 0;
    sigs.push({ name: qualifiedName(d.name ?? d.class ?? f.title.split('/').pop(), `rewiki_${f.kind}`), pattern: pattern.trim().toUpperCase().replace(/\?\??/g, '??'), kind: f.kind, status: f.status, fact: f.title, prototype: typeof d.prototype === 'string' ? d.prototype : undefined, offset, multiple: d.multiple === true });
  }
  const ascii = (x: string) => JSON.stringify(x.replace(/[^\x20-\x7e]/g, '?'));
  const list = sigs.map((x) => `    (${ascii(x.name)}, ${ascii(x.pattern)}, ${ascii(x.kind)}, ${ascii(x.status)}, ${ascii(x.fact)}, ${x.offset}, ${x.multiple ? 'True' : 'False'}),`).join('\n');
  const head = `# ${HEADER_NOTE}\n# Signatures of: ${comment(subject)}\n# Generated: ${new Date().toISOString()}\n`;
  let script: string;
  if (args.tool === 'json' || args.tool === 'sym') script = JSON.stringify({ subject, signatures: sigs }, null, 2);
  else if (args.tool === 'ghidra') {
    script = `${head}# Run in Ghidra's Script Manager (Jython or PyGhidra) with your program open. It searches the program
# for each signature and names a match only when it is unique; data tables (kind "global") compiled in
# more than once, and signatures marked multiple (thunks, inlined helpers), get every copy named (_2, _3...).
# Set LABEL_ALL = True to do that for every signature.
from ghidra.program.model.symbol import SourceType

LABEL_ALL = False
MAX_COPIES = 16

SIGNATURES = [
${list}
]

def to_regex(pattern):
    return "".join("[\\\\x00-\\\\xff]" if b == "??" else "\\\\x" + b for b in pattern.split())

named = 0
for name, pattern, kind, status, fact, offset, multiple in SIGNATURES:
    every = LABEL_ALL or multiple or kind == "global"
    hits = findBytes(currentProgram.getMinAddress(), to_regex(pattern), MAX_COPIES if every else 2)
    if not hits or (len(hits) > 1 and not every):
        print("%s: %d matches, not named" % (name, len(hits)))
        continue
    for i, hit in enumerate(hits):
        addr = hit.add(offset)
        label = name if i == 0 else "%s_%d" % (name, i + 1)
        if kind == "function" and getFunctionAt(addr) is None:
            createFunction(addr, label)
        createLabel(addr, label, True, SourceType.USER_DEFINED)
        setPlateComment(addr, "ReverseEngineering.wiki [%s] %s (signature match)" % (status, fact))
    named += 1
print("ReverseEngineering.wiki: named %d of %d signatures" % (named, len(SIGNATURES)))
`;
  } else {
    script = `${head}# Run in IDA via File > Script file (IDAPython) with your database open. It searches for each signature
# and names a match only when it is unique; data tables (kind "global") compiled in more than once get
# every copy named (_2, _3...), and so do signatures marked multiple. Set LABEL_ALL = True for all of them.
import idaapi, idc, ida_bytes, ida_funcs, ida_name

LABEL_ALL = False
MAX_COPIES = 16

SIGNATURES = [
${list}
]

def find_all(pattern, limit=2):
    hits, ea, end = [], idaapi.inf_get_min_ea(), idaapi.inf_get_max_ea()
    pat = pattern.replace("??", "?")
    while len(hits) < limit:
        try:
            ea = ida_bytes.find_bytes(pat, ea, range_end=end)
        except AttributeError:
            ea = idc.find_binary(ea, idc.SEARCH_DOWN, pat)
        if ea == idaapi.BADADDR:
            break
        hits.append(ea)
        ea += 1
    return hits

named = 0
for name, pattern, kind, status, fact, offset, multiple in SIGNATURES:
    every = LABEL_ALL or multiple or kind == "global"
    hits = find_all(pattern, MAX_COPIES if every else 2)
    if not hits or (len(hits) > 1 and not every):
        print("%s: %d matches, not named" % (name, len(hits)))
        continue
    for i, hit in enumerate(hits):
        ea = hit + offset
        label = name if i == 0 else "%s_%d" % (name, i + 1)
        if kind == "function":
            ida_funcs.add_func(ea)
        ida_name.set_name(ea, label, ida_name.SN_NOWARN | ida_name.SN_NOCHECK | ida_name.SN_FORCE)
        idc.set_cmt(ea, "ReverseEngineering.wiki [%s] %s (signature match)" % (status, fact), 1)
    named += 1
print("ReverseEngineering.wiki: named %d of %d signatures" % (named, len(SIGNATURES)))
`;
  }
  return {
    subject, tool: args.tool, signatures: sigs.length, script,
    hint: sigs.length ? undefined : 'No signature facts on this subject yet: add_fact with data.signature (bytes with ?? wildcards).',
    warning: 'Review generated scripts before running. A function signature that matches more than once is reported, not applied; data tables name every copy.',
  };
}

export function exportSymbols(s: Services, args: { build?: string; platform?: string; subject?: string; tool: SymbolTool }) {
  if (!args.build && !args.platform && !args.subject) throw new ToolError('BAD_REQUEST', 'Give build (an exact binary), platform (its fixed hardware addresses) or subject (a script that finds its signatures in your binary).');
  if (args.subject && !args.build) return exportSignatureScan(s, { subject: args.subject, tool: args.tool });
  if (args.platform && !args.build) return exportPlatformSymbols(s, { platform: args.platform, tool: args.tool });
  const build = s.index.resolveRedirect(cleanTitle(args.build!, ['build']));
  if (!s.index.page(build)) throw new ToolError('NOT_FOUND', `"${build}" is not a known build. Use lookup_binary or register_build.`);
  const rows = s.index.factsForBuild(build).filter((f) => ['function', 'global', 'vtable'].includes(f.kind) && f.status !== 'rejected');
  // rva: relative to the image base (PE); absolute: a fixed address (PlayStation, consoles, va facts).
  const symbols: Array<{ rva: number; name: string; kind: string; status: string; fact: string; absolute?: boolean }> = [];
  const signatureOnly: Array<{ name: string; pattern: string; fact: string }> = [];
  const otherAddresses: Array<{ name: string; kind: string; value: string; fact: string }> = [];
  for (const f of rows) {
    const data = JSON.parse(f.data);
    const rva = hexNum(data.rva);
    const name = qualifiedName(data.name ?? data.class, `rewiki_${f.kind}`);
    const va = data.address?.kind === 'va' ? hexNum(data.address.value) : null;
    if (rva !== null) symbols.push({ rva, name, kind: f.kind, status: f.status, fact: f.title });
    else if (va !== null) symbols.push({ rva: va, name, kind: f.kind, status: f.status, fact: f.title, absolute: true });
    else if (data.address && typeof data.address.value === 'string') otherAddresses.push({ name, kind: String(data.address.kind), value: data.address.value, fact: f.title });
    else if (typeof data.signature === 'string') signatureOnly.push({ name, pattern: data.signature, fact: f.title });
  }
  // The build's symbol map fills in every address no fact covers (facts win: they carry evidence).
  const byFact = new Set(symbols.map((x) => x.rva));
  let fromMap = 0;
  for (const m of s.index.symbolsForBuild(build)) {
    if (byFact.has(m.rva) || (m.kind !== 'function' && m.kind !== 'global' && m.kind !== 'vtable' && m.kind !== 'label')) continue;
    symbols.push({ rva: m.rva, name: qualifiedName(m.name, `rewiki_${m.kind}`), kind: m.kind === 'label' ? 'global' : m.kind, status: `map:${m.confidence}`, fact: m.title, absolute: !!m.absolute });
    fromMap++;
  }
  symbols.sort((a, b) => a.rva - b.rva);
  const ascii = (x: string) => JSON.stringify(x.replace(/[^\x20-\x7e]/g, '?'));
  const pyList = symbols.map((x) => `    (0x${x.rva.toString(16)}, ${ascii(x.name)}, ${ascii(x.kind)}, ${ascii(x.status)}, ${ascii(x.fact)}, ${x.absolute ? 'True' : 'False'}),`).join('\n');
  const pySigs = [
    ...signatureOnly.map((x) => `#   ${comment(x.name)}: pattern ${comment(x.pattern)}  (${comment(x.fact)})`),
    ...otherAddresses.map((x) => `#   ${comment(x.name)}: ${comment(x.kind)} address ${comment(x.value)}  (${comment(x.fact)})`),
  ].join('\n');
  const head = `# ${HEADER_NOTE}\n# Build: ${comment(build)}\n# Generated: ${new Date().toISOString()}\n`;

  let script: string;
  if (args.tool === 'sym') {
    // bank:address name (RGBDS, BGB, mGBA and most retro debuggers): banked facts as they are.
    const banked = otherAddresses.filter((x) => x.kind === 'banked').map((x) => {
      const [bank, addr] = x.value.split(':');
      return `${bank.toUpperCase().padStart(2, '0')}:${addr.toUpperCase().padStart(4, '0')} ${x.name}`;
    });
    script = `; ${HEADER_NOTE}\n; Build: ${comment(build)}\n${banked.sort().join('\n')}\n`;
  } else if (args.tool === 'json') {
    const hex = (n: number) => `0x${n.toString(16).toUpperCase()}`;
    script = JSON.stringify({ build, symbols: symbols.map((x) => ({ ...x, rva: x.absolute ? undefined : hex(x.rva), va: x.absolute ? hex(x.rva) : undefined })), signature_only: signatureOnly, other_addresses: otherAddresses }, null, 2);
  } else if (args.tool === 'ghidra') {
    script = `${head}# Run in Ghidra's Script Manager (Jython or PyGhidra) with the program open.
from ghidra.program.model.symbol import SourceType

SYMBOLS = [
${pyList}
]

base = currentProgram.getImageBase()
for rva, name, kind, status, fact, absolute in SYMBOLS:
    addr = toAddr(rva) if absolute else base.add(rva)
    if kind == "function" and getFunctionAt(addr) is None:
        createFunction(addr, name)
    createLabel(addr, name, True, SourceType.USER_DEFINED)
    setPlateComment(addr, "ReverseEngineering.wiki [%s] %s" % (status, fact))
print("ReverseEngineering.wiki: applied %d symbols" % len(SYMBOLS))
${pySigs ? `\n# Not applied automatically (signature only, or a segmented, banked or file-offset address):\n${pySigs}\n` : ''}`;
  } else {
    script = `${head}# Run in IDA via File > Script file (IDAPython).
import idaapi, idc, ida_funcs, ida_name

SYMBOLS = [
${pyList}
]

base = idaapi.get_imagebase()
for rva, name, kind, status, fact, absolute in SYMBOLS:
    ea = rva if absolute else base + rva
    if kind == "function":
        ida_funcs.add_func(ea)
    ida_name.set_name(ea, name, ida_name.SN_NOWARN | ida_name.SN_NOCHECK | ida_name.SN_FORCE)
    idc.set_cmt(ea, "ReverseEngineering.wiki [%s] %s" % (status, fact), 1)
print("ReverseEngineering.wiki: applied %d symbols" % len(SYMBOLS))
${pySigs ? `\n# Not applied automatically (signature only, or a segmented, banked or file-offset address):\n${pySigs}\n` : ''}`;
  }
  return {
    build, tool: args.tool, symbols: symbols.length, from_facts: symbols.length - fromMap, from_symbol_map: fromMap, signature_only: signatureOnly.length, other_addresses: otherAddresses.length, script,
    warning: 'Review generated scripts before running. Names come from community facts (status claimed/verified) and the symbol map (status map:<confidence>).',
  };
}
